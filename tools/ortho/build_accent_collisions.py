#!/usr/bin/env python3
"""CC-ORTHO-FIX-FIL-ROMANCE F3/F4: write data/<lang>/accent-collisions.tsv (es, fr, pt) and the Spell Jr exclusions.

Every pair of bank rows that differ only in accent marks is a real-word collision. Default sound = different (stress or
vowel quality changes: trabajo/trabajó, fr -e/-é). The pairs below are named SAME-sound by the spec (Eric 2026-11-06) or
are tilde-only pairs tagged for the Gig B 'Same sound?' column; the auditor confirms every row. Pairs the spec names that
are not bank rows (es te/té, fr ou/où, pt avó/avô...) are listed so the grader knows they are real words (no bank row added).

Different-sound pairs whose members are bank rows go onto the language's Spell Jr exclusion list (hand-written part, above
the generated marker), inside a block this script owns. python3 tools/ortho/build_accent_collisions.py [--check]
"""
import os, sys, unicodedata as u, collections
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
T = "easy medium hard expert".split()
nfc = lambda s: u.normalize("NFC", s)
def base(w): return nfc("".join(c for c in u.normalize("NFD", w) if not "̀" <= c <= "ͯ"))
SAME = {
 "es": [("donde","dónde"),("quien","quién"),("te","té"),("si","sí"),("tu","tú"),("el","él"),("mas","más"),("mi","mí"),("se","sé"),("de","dé")],
 "fr": [("ou","où"),("a","à"),("la","là"),("sur","sûr")],
 "pt": [("porque","porquê")],
}
DIFF_FIXTURES = {
 "es": [("esta","está"),("ano","año"),("caza","cazá")][:2],
 "fr": [("pêche","péché")],
 "pt": [("avo","avó"),("avó","avô"),("caca","caça")],
}
BEGIN = "# --- CC-ORTHO-FIX F3 begin: different-sound accent-only pairs, generated by tools/ortho/build_accent_collisions.py ---"
END = "# --- CC-ORTHO-FIX F3 end ---"

def bank(lang):
    d = set()
    for t in T:
        for w in open(f"{REPO}/assets/words/{lang}/{t}.txt", encoding="utf-8"):
            w = nfc(w.strip().lower())
            if w and w.isalpha(): d.add(w)
    return d

def build(lang):
    B = bank(lang)
    g = collections.defaultdict(set)
    for w in B: g[base(w)].add(w)
    rows, seen = [], set()
    def add(a, b, sound, src):
        k = tuple(sorted((a, b)))
        if k in seen: return
        seen.add(k); rows.append((a, b, sound, src))
    same_keys = {tuple(sorted(p)) for p in SAME[lang]}
    for p in SAME[lang]:
        add(*p, "same", "named by the spec, or tilde-only and tagged for Gig B; auditor confirms" + ("" if all(x in B for x in p) else "; not a bank row"))
    for p in DIFF_FIXTURES[lang]:
        add(*p, "different", "named by the spec; not a bank row" if not all(x in B for x in p) else "named by the spec")
    for ws in sorted(g.values(), key=sorted):
        ws = sorted(ws)
        for i, a in enumerate(ws):
            for b in ws[i+1:]:
                add(a, b, "different", "bank pair; default different sound (stress or vowel quality); auditor confirms")
    return B, rows

def main():
    check = "--check" in sys.argv; bad = 0
    for lang in ("es", "fr", "pt"):
        B, rows = build(lang)
        out = "# CC-ORTHO-FIX-FIL-ROMANCE F3/F4 accent-only collisions. a\tb\tsound\tsource. Generated, do not hand-edit.\n" + \
              "".join("\t".join(r) + "\n" for r in rows)
        path = f"{REPO}/data/{lang}/accent-collisions.tsv"
        kid = f"{REPO}/assets/words/kid-exclude/{lang}.txt"
        ex = sorted({w for a, b, s, _ in rows if s == "different" for w in (a, b) if w in B})
        cur = open(kid, encoding="utf-8").read() if os.path.exists(kid) else ""
        if BEGIN in cur: cur = cur.split(BEGIN)[0] + (cur.split(END, 1)[1].lstrip("\n") if END in cur else "")
        mark = "# --- CC-BANK-PURITY F7 seed"
        block = BEGIN + "\n" + "".join(w + "\n" for w in ex) + END + "\n"
        if mark in cur:
            i = cur.index(mark); newkid = cur[:i].rstrip("\n") + "\n" + block + cur[i:]
        else:
            newkid = cur.rstrip("\n") + "\n" + block
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != out or newkid != cur_orig(kid): bad += 1; print(lang, "drift")
        else:
            open(path, "w", encoding="utf-8").write(out); open(kid, "w", encoding="utf-8").write(newkid)
        print(lang, len(rows), "pairs,", len(ex), "Jr exclusions")
    sys.exit(1 if bad else 0)
def cur_orig(p): return open(p, encoding="utf-8").read()
main()
