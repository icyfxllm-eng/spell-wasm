#!/usr/bin/env python3
"""CC-ORTHO-FIX-FIL-ROMANCE 4: data/saved-word-map.tsv, the old -> stored map the app uses to repair saved Misses and My Words.

    python3 tools/ortho/build_saved_word_map.py [--check]

A row is `lang<TAB>old<TAB>new<TAB>source`. `new` empty means HIDDEN: the old form is a quarantined row with no stored twin (not Filipino,
only root + linker, ...); the app keeps it in storage but never serves it. Scope is exactly fil es fr pt vi hi ru zh (Eric 4d).
Sources of `old`: every row the CC-ORTHO-SWEEP-ALL batches quarantined (the manifest, evidence starting "CC-ORTHO-SWEEP-ALL:") and the
three pt forms renamed in place. Sources of `new`: the accepted-variants files (variant -> stored), the Russian pair verdicts, and a short
explicit list of misspelling twins. Exits 2 if any old form maps to two different stored forms, or an old form is a current row.
"""
import csv, os, sys, unicodedata
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
nfc = lambda s: unicodedata.normalize("NFC", s)
SCOPE = "fil es fr pt vi hi ru zh".split()
TAG = "CC-ORTHO-SWEEP-ALL:"
TIERS = "easy medium hard expert".split()
PT_RENAMED = [("pára", "para"), ("dêem", "deem"), ("facto", "fato")]
EXPLICIT = {  # misspelling twins that have no variant row
    ("vi", "đựơc"): "được", ("fil", "kuponan"): "koponan", ("fil", "kabuoan"): "kabuuan",
    ("fil", "espirito"): "espiritu", ("fil", "sunud-sunod"): "sunod-sunod",
    ("zh", "hu2li2|狐狸"): "hu2li5|狐狸", ("zh", "you3zhu4|有着"): "you3zhe5|有着",
}

def bank(lang):
    out = set()
    if lang == "zh":   # the app serves zh from the ZH_* consts in src/words.rs (build-zh-bank.py), not from assets/words/zh
        import re
        w = open(f"{REPO}/src/words.rs", encoding="utf-8").read()
        for t in ("EASY", "MEDIUM", "HARD", "EXPERT"):
            m = re.search(r"pub const ZH_%s: &\[&str\] = &\[(.*?)\n\];" % t, w, re.S)
            out |= {nfc(x) for x in re.findall(r'"([^"]+)"', m.group(1))}
        return out
    for t in TIERS:
        p = f"{REPO}/assets/words/{lang}/{t}.txt"
        if os.path.exists(p): out |= {nfc(w.strip()) for w in open(p, encoding="utf-8").read().split("\n") if w.strip()}
    return out

def build():
    banks = {l: bank(l) for l in SCOPE}
    old = {}   # (lang, old) -> source
    for r in csv.reader(open(f"{REPO}/assets/words-quarantine/manifest.csv", encoding="utf-8")):
        if len(r) > 5 and r[0] in SCOPE and r[5].startswith(TAG): old[(r[0], nfc(r[1]))] = f"quarantine:{r[4]}"
    for o, n in PT_RENAMED: old[("pt", nfc(o))] = "renamed_in_place"
    twin = {}  # (lang, old) -> set of news
    def add(l, o, n, why):
        twin.setdefault((l, nfc(o)), {})[nfc(n)] = why
    for l in SCOPE:
        p = f"{REPO}/data/{l}/accepted-variants.tsv"
        if os.path.exists(p):
            for ln in open(p, encoding="utf-8").read().split("\n"):
                if ln and not ln.startswith("#"):
                    s, a = ln.split("\t")[:2]
                    if (l, nfc(a)) in old and nfc(s) in banks[l]: add(l, a, s, "variant")
    for ln in open(f"{REPO}/reports/ortho-census/ru-yo-pairs.tsv", encoding="utf-8").read().split("\n")[1:]:
        if ln:
            yo, e, verdict = ln.split("\t")
            if (("ru", nfc(e)) in old) and verdict.startswith("quarantine"): add("ru", e, yo, "ru_yo_pair")
    for (l, o), n in EXPLICIT.items():
        if (l, nfc(o)) in old: add(l, o, n, "explicit")
    rows, bad = [], []
    for (l, o), src in sorted(old.items()):
        if o in banks[l]:
            if l == "zh": print(f"NOT EFFECTIVE IN THE APP, left out of the map: zh {o!r} is still served from src/words.rs"); continue
            bad.append(f"{l} {o!r} is a current bank row"); continue
        news = twin.get((l, o), {})
        if len(news) > 1: bad.append(f"{l} {o!r} maps to two stored forms: {sorted(news)}"); continue
        if news:
            (n, why), = news.items()
            if n not in banks[l]: bad.append(f"{l} {o!r} -> {n!r} is not a bank row"); continue
            rows.append((l, o, n, f"{src};{why}"))
        else: rows.append((l, o, "", f"{src};hidden"))
    return rows, bad

def main():
    rows, bad = build()
    for b in bad: print("SAVED-WORD-MAP FAIL:", b)
    if bad: sys.exit(2)
    text = "# CC-ORTHO-FIX-FIL-ROMANCE 4: generated by tools/ortho/build_saved_word_map.py. lang<TAB>old<TAB>new (empty = hidden)<TAB>source\n" + "".join("\t".join(r) + "\n" for r in rows)
    p = f"{REPO}/data/saved-word-map.tsv"
    if "--check" in sys.argv:
        ok = os.path.exists(p) and open(p, encoding="utf-8").read() == text
        print("saved-word-map: OK" if ok else "saved-word-map: STALE -- run tools/ortho/build_saved_word_map.py"); sys.exit(0 if ok else 1)
    open(p, "w", encoding="utf-8").write(text)
    import collections
    print(len(rows), "rows;", dict(collections.Counter(r[0] for r in rows)), "| hidden", sum(1 for r in rows if not r[2]))
main()
