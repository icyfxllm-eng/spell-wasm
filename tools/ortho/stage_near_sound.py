#!/usr/bin/env python3
"""CC-ORTHO-SWEEP-DE-JA v1.1 F7/F8, staged as DATA ONLY. Rebuilds data/de/near-sound-candidates.tsv, data/de/homophone-candidates.tsv,
data/ja/near-sound-candidates.tsv and data/ja/devoicing-pairs.tsv from the census candidates (reports/ortho-census/) and the current banks.
Nothing consumes the outputs. Eric's rules (2026-11-04):
  de  final devoicing: d/t before a consonant or at word end = homophone (-> SENSE-CUE table candidates); between vowels = near-sound.
      Silent-h and ie/i pairs that sound identical are homophones too.
  ja  a pair member must be a dictionary-verified bank row (so no fragment, name or slur can be in a pair); devoicing sites are minimal pairs."""
import os, sys, csv
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, f"{REPO}/tools/bank")
import purity_gate as g
CEN = f"{REPO}/reports/ortho-census"
CONS = set("bcdfghjklmnpqrstvwxzß")

def rows(p): return [l.rstrip("\n").split("\t") for l in open(p, encoding="utf-8") if l.strip() and not l.startswith("#")]
de_bank = {w.lower() for _, w in g.bank(REPO, "de")}
ja_bank = {w for _, w in g.bank(REPO, "ja")}
REMOVAL_CANDIDATES = {"いっつも", "すっごい", "でっかい", "いやぁ", "てぇ"}      # colloquial / small-kana spellings: reported to Eric as bank-removal candidates, never paired
PROF = {l.strip() for l in open(f"{REPO}/assets/words/profanity/ja.txt", encoding="utf-8")}
ja_ok = {l.split("\t")[0] for l in g.lines(f"{REPO}/assets/words/purity/ja.tsv") if l.split("\t")[1] in ("dictionary", "exception")} & ja_bank - REMOVAL_CANDIDATES - PROF

# ---- de
HOMO_SILENT = {("wahren", "waren"): "silent lengthening h", ("wider", "wieder"): "ie = long i", ("liegen", "ligen"): "ie = long i (Ligen, plural of Liga)",
               ("booten", "boten"): "oo = o, both long"}
def devoiced(w, other):
    """True when the d/t that differs sits before a consonant or at word end (final devoicing neutralises it)."""
    i = next((k for k in range(min(len(w), len(other))) if w[k] != other[k]), None)
    if i is None or {w[i], other[i]} != {"d", "t"}: return False
    nxt = w[i + 1] if i + 1 < len(w) else ""
    return nxt == "" or nxt in CONS
near, homo = [], []
for r in rows(f"{CEN}/C7_de_near_sound_candidates.tsv"):
    a, b, rule = r[0].lower(), r[1].lower(), r[2]
    if a not in de_bank or b not in de_bank: continue
    key = tuple(sorted((a, b)))
    if key in HOMO_SILENT: homo.append((key[0], key[1], HOMO_SILENT[key])); continue
    if rule.startswith("EXTRA:"): rule = rule[6:]
    if "t<->d" in rule:
        if devoiced(a, b): homo.append((key[0], key[1], "final devoicing: d/t before a consonant or at word end")); continue
        rule = "t-d-voicing"                       # boden/booten and boden/boten differ only in d/t between vowels: oo and o are both long, so no vowel label
    near.append((a, b, rule))
# ---- ja
NEAR = [(r[0], r[1], r[2]) for r in rows(f"{CEN}/C8_ja_near_sound_candidates.tsv") if r[0] in ja_ok and r[1] in ja_ok]
dropped = [(r[0], r[1]) for r in rows(f"{CEN}/C8_ja_near_sound_candidates.tsv") if not (r[0] in ja_ok and r[1] in ja_ok)]
# ---- devoicing minimal pairs
VL = set("かきくけこさしすせそたちつてとはひふへほぱぴぷぺぽ")
SWAP = {"き": "く", "く": "き", "し": "す", "す": "し", "ひ": "ふ", "ふ": "ひ", "ぴ": "ぷ", "ぷ": "ぴ"}
def morae(w):
    out = []
    for c in w:
        if c in "ゃゅょ" and out: out[-1] += c
        else: out.append(c)
    return out
def site(m, i):
    """firm / final / None for mora i being devoiced (i/u after a voiceless consonant, next mora voiceless)."""
    if m[i] not in SWAP: return None
    j = i + 1 + (1 if i + 1 < len(m) and m[i + 1] == "っ" else 0)
    if j < len(m): return "firm" if m[j][0] in VL else None
    return "final" if m[i] in "しす" else None
dev = {}
for w in sorted(ja_ok):
    m = morae(w)
    for i, x in enumerate(m):
        s = site(m, i)
        if not s: continue
        v = "".join(m[:i] + [SWAP[x]] + m[i + 1:])
        if v in ja_ok and v != w:
            key = tuple(sorted((w, v)))
            dev[key] = (i + 1, "optional (word-final し/す)" if s == "final" else "devoiced")
def out(path, head, rows_):
    with open(f"{REPO}/{path}", "w", encoding="utf-8") as f:
        f.write(head + "\n"); [f.write("\t".join(map(str, r)) + "\n") for r in rows_]
GEN = "Generated by tools/ortho/stage_near_sound.py; nothing consumes this file."
out("data/de/near-sound-candidates.tsv", f"# CC-ORTHO-SWEEP-DE-JA v1.1 F7, STAGED AS DATA ONLY (de). Near-sound pairs: a<TAB>b<TAB>rule. No pair here is a true homophone ({GEN})\n# F7/F8 stay held until CC-VOICE-CLARITY v1.1 (intake format) is committed. d/t differing between vowels is near-sound; before a consonant or at word end it is a homophone (final devoicing) and is in data/de/homophone-candidates.tsv.", sorted(near))
out("data/de/homophone-candidates.tsv", f"# CC-ORTHO-SWEEP-DE-JA v1.1: true German homophones found by the near-sound census, for the CC-SENSE-CUE sound-alike table. a<TAB>b<TAB>why. {GEN}\n# NOT yet in assets/words/de/homophones.seed.txt: build_collisions merges that file into grading (accept-any), so adding it is a grading change that needs Eric's go.", sorted(homo))
out("data/ja/near-sound-candidates.tsv", f"# CC-ORTHO-SWEEP-DE-JA v1.1 F8, STAGED AS DATA ONLY (ja). Near-sound pairs: a<TAB>b<TAB>rule. Both members are dictionary-verified bank rows after the ja PURITY batch ({GEN})\n# F7/F8 stay held until CC-VOICE-CLARITY v1.1 (intake format) is committed. Spelling variants live in data/ja/accepted-variants.tsv, not here.", sorted(NEAR))
out("data/ja/devoicing-pairs.tsv", f"# CC-ORTHO-SWEEP-DE-JA v1.1 F8, STAGED AS DATA ONLY (ja). Devoicing minimal pairs: a<TAB>b<TAB>mora (1-based)<TAB>site. Two bank words that differ only in the vowel (i/u) of one devoiced mora. {GEN}", [(k[0], k[1], *v) for k, v in sorted(dev.items())])
print(len(near), "de near;", len(homo), "de homophones;", len(NEAR), "ja near (", len(dropped), "dropped );", len(dev), "devoicing pairs")
print("homophones:", homo); print("de near:", near)
