#!/usr/bin/env python3
"""Re-emit the four ZH_* consts in src/words.rs from assets/words/zh/*.txt, exactly as scripts/build-zh-bank.py step 5 does and with
none of its corpus step (no network, no new rows). zh is the one language whose served bank is NOT generated by build-wordlists.py,
so a quarantine in assets/words/zh does not reach the app until this runs. [--check] exits 1 if words.rs is stale."""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WORDS_RS, ZH_DIR = f"{ROOT}/src/words.rs", f"{ROOT}/assets/words/zh"
src = open(WORDS_RS, encoding="utf-8").read(); out = src
for tier in ("easy", "medium", "hard", "expert"):
    rows = [l.strip() for l in open(f"{ZH_DIR}/{tier}.txt", encoding="utf-8") if l.strip()]
    block = f"pub const ZH_{tier.upper()}: &[&str] = &[\n" + "".join(f'    "{p}",\n' for p in rows) + "];"
    out = re.sub(rf"pub const ZH_{tier.upper()}: &\[&str\] = &\[.*?\];", lambda _m: block, out, count=1, flags=re.S)
if "--check" in sys.argv:
    print("zh-words-rs: OK" if out == src else "zh-words-rs: STALE -- run tools/ortho/sync_zh_words_rs.py"); sys.exit(0 if out == src else 1)
open(WORDS_RS, "w", encoding="utf-8").write(out)
print("rewritten" if out != src else "unchanged")
