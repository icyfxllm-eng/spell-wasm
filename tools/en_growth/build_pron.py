#!/usr/bin/env python3
"""F1 -- English pronunciation keys. Writes assets/words/en/en_pron.json.

Key = every CMUdict pronunciation of the row, ARPAbet, stress stripped. A row with
no CMUdict entry is listed under "null" and never guessed (fail closed).
Extra words (calibration set, staged candidates) can be passed with --extra FILE.
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *

ap = argparse.ArgumentParser()
ap.add_argument("--extra", help="file of extra words, one per line")
ap.add_argument("--out", default=os.path.join(ROOT, "assets/words/en/en_pron.json"))
a = ap.parse_args()
cmu = load_cmu()
b = bank_rows()
words = [w for t in TIERS for w in b[t]]
if a.extra:
    words += [l.strip() for l in open(a.extra, encoding="utf-8") if l.strip() and not l.startswith("#")]
words = sorted(set(words))
keys, nul = {}, []
for w in words:
    if w in cmu:
        keys[w] = [" ".join(p) for p in cmu[w]]
    else:
        nul.append(w)
doc = {
    "$doc": "CC-EN-EXPERT-GROWTH F1. ARPAbet, stress stripped, all pronunciations. Generated by tools/en_growth/build_pron.py; do not edit.",
    "source": {"name": "CMUdict", "licence": "BSD-style (tools/wordpipe/sources/cmudict.LICENSE)", "sha256": sha256_file(CMU)},
    "bank_hash": bank_hash(),
    "keys": keys,
    "null": nul,
}
json.dump(doc, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, indent=0, sort_keys=True)
open(a.out, "a").write("\n")
print(f"{len(keys)} keyed, {len(nul)} null: {nul}")
