/// D17 is scoped to 12×12; D19 cuts 12×12 Number Mode; Spell Jr never sees it.
#[test]
fn twelve_rules() {
    assert_eq!(super::play::unlock_after_on(12, Tier::Expert), Some(3));
    assert_eq!(super::play::unlock_after_on(9, Tier::Expert), None, "a 9x9 Expert board still spells every commit");
    assert!(is_word_mode(false, 12, Tier::Expert));
    let en = super::table::load("en").unwrap();
    assert!(board_or_number("en", false, &config12(), 1, &Personal::default(), Some(&en)).is_none(), "no 12x12 Number Mode");
    assert!(!super::play::allowed(true, 12, Tier::Expert), "Spell Jr never gets 12x12");
    assert!(super::play::allowed(false, 12, Tier::Expert));
}

