const LANGS: &[&str] = &["en", "es", "fr", "de", "pt", "pl", "ru", "vi", "ko", "ja", "zh", "fil", "sw", "ar", "hi"];

/// A 12×12 board: unique, graded Expert with its fragment, the fragment
/// necessary, the 8 expert + 4 hard mix (F12), no free spelling (I12), and
/// exactly 36 full spellings to finish it (D17).
fn check_twelve(b: &super::bind::Board) {
    let p = &b.puzzle;
    assert_eq!(p.n, 12);
    let geo = Geo::new(S12);
    let (fixed, restrict) = p.constraints(&b.symbols());
    assert_eq!(count_solutions(&geo, &fixed, &restrict, 2), 1, "{}: I1", b.lang);
    assert_eq!(grade(&geo, &fixed, &restrict), Some(Tier::Expert.tech()), "{}: I2", b.lang);
    let frag = (0..144).filter(|&i| matches!(p.clues[i], Clue::Fragment(_))).any(|i| {
        let mut open = restrict.clone();
        open[i] = geo.full();
        count_solutions(&geo, &fixed, &open, 2) > 1
    });
    assert!(frag, "{}: a necessary fragment", b.lang);
    let Mode::Words(w) = &b.mode else { panic!("12x12 is Word Mode only (D19)") };
    for &(band, count) in band_mix(12, Tier::Expert).unwrap() {
        assert_eq!(w.iter().filter(|s| s.band == band).count(), count, "{}: F12 mix", b.lang);
    }
    let glyphs: std::collections::HashSet<String> = w.iter().map(|s| s.glyph.to_lowercase()).collect();
    assert_eq!(glyphs.len(), 12, "{}: I11", b.lang);
    assert!(!b.spells_a_symbol(), "{}: I12", b.lang);
    // D17 / Done #21: at N=3, every symbol is spelled three times before its chip.
    let need = super::play::unlock_after_on(12, Tier::Expert).unwrap() as usize;
    let spellings: usize = (1..=12u8)
        .map(|v| (0..144).filter(|&i| p.solution[i] == v && !matches!(p.clues[i], Clue::Given(_) | Clue::Spelled(_))).count().min(need))
        .sum();
    assert_eq!(spellings, 36, "{}: Done #21 wants 36 full spellings", b.lang);
}

fn viability(per_lang: usize) {
    let es = entries();
    for lang in LANGS {
        let mut ok = 0;
        for k in 0..per_lang {
            let e = &es[(k * 37) % es.len()];
            if let Some(b) = board_from_pack(lang, e, 900 + k as u64, &Personal::default()) {
                check_twelve(&b);
                ok += 1;
            }
        }
        // Done #19: at least 95%, or the language would not offer 12×12.
        assert!(ok * 100 >= per_lang * 95, "{lang}: 12x12 viable in {ok} of {per_lang}");
    }
}

