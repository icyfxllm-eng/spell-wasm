/// How many distinct grids the pack carries: more than a player meets in the
/// 365-day repeat window (I6) at several 12×12 boards a day.
pub const PACK_SIZE: usize = 1000;

fn pack_seed(i: u64) -> u64 {
    fnv(format!("spelldoku-pack12|{i}").as_bytes())
}

/// Writes assets/spelldoku/pack12.json. Deterministic: the same seeds, the
/// same order, on any machine.
/// cargo test --release --lib --features audit_preview build_pack12 -- --ignored
#[test]
#[ignore]
fn build_pack12() {
    let want = PACK_SIZE + PACK_SIZE / 10;
    let threads = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4) as u64;
    let handles: Vec<_> = (0..threads)
        .map(|t| {
            std::thread::spawn(move || {
                let mut found: Vec<(u64, Entry)> = Vec::new();
                let mut i = t;
                while (i as usize) < want {
                    let seed = pack_seed(i);
                    if let Some(e) = (0..4000u64).find_map(|a| entry_for(seed, a)) {
                        found.push((i, e));
                    }
                    i += threads;
                }
                found
            })
        })
        .collect();
    let mut all: Vec<(u64, Entry)> = handles.into_iter().flat_map(|h| h.join().unwrap()).collect();
    all.sort_by_key(|(i, _)| *i);
    let mut seen = std::collections::HashSet::new();
    let entries: Vec<Entry> = all.into_iter().map(|(_, e)| e).filter(|e| seen.insert(e.hash)).take(PACK_SIZE).collect();
    assert_eq!(entries.len(), PACK_SIZE, "not enough distinct grids");
    let body = serde_json::json!({
        "$comment": "GENERATED by src/spelldoku/pack_tests.rs build_pack12 -- do not edit. CC-SPELLDOKU v1.2 D18: 12x12 Expert (seed, attempt) pairs whose grid grades exactly Expert and leaves every symbol three empty cells; hash is the grid's canonical hash (I6). Symbols are bound on the device.",
        "entries": entries,
    });
    let path = format!("{}/assets/spelldoku/pack12.json", env!("CARGO_MANIFEST_DIR"));
    std::fs::write(path, format!("{:#}\n", body)).unwrap();
}

fn check(e: &Entry) {
    let fixed = grid_at(e.seed, e.attempt, &config12()).unwrap_or_else(|| panic!("entry {:x}/{} no longer grades Expert", e.seed, e.attempt));
    let geo = Geo::new(S12);
    let open = vec![geo.full(); 144];
    assert_eq!(count_solutions(&geo, &fixed, &open, 2), 1, "I1: {:x} is not unique", e.seed);
    assert_eq!(grade(&geo, &fixed, &open), Some(Tier::Expert.tech()), "I2: {:x} graded wrong", e.seed);
    assert!(three_empties_each(&fixed), "D17: every symbol keeps three empty cells");
    assert_eq!(entry_for(e.seed, e.attempt), Some(*e), "the recorded hash reproduces");
}

/// Done #20 at gate size: pack entries rebuild exactly, unique and graded.
#[test]
fn pack_entries_rebuild_unique_and_expert() {
    let es = entries();
    assert_eq!(es.len(), PACK_SIZE, "the pack is present");
    let hashes: std::collections::HashSet<u64> = es.iter().map(|e| e.hash).collect();
    assert_eq!(hashes.len(), es.len(), "I6: no two entries are the same grid");
    for e in es.iter().step_by(97) {
        check(e);
    }
}

